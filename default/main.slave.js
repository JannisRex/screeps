let doSpawn = require('task.spawn')
let doMine = require('task.mine')
let doWithdrawEnergy = require('task.withdrawEnergy')
let doUpgrade = require('task.upgrade')
let doCharge = require('task.charge')
let doBuild = require('task.build')
let doRepair = require('task.repair')

let constants = require('lib.constants')
const maxCreepParts = constants.maxCreepParts

// FIXME: is new too expensive?
/* new Slave(creep)
 *
 * Creates a Slave object out of a creep. The creep must be able to at least do
 * CARRY, WORK, MOVE.
 */
let Slave = function (creep) {
  this.creep = creep
}

// returns the role of the creep
Slave.prototype.role = function () {
  return this.creep.memory.role
}
// returns the mode of the creep, defaults to 'mine'
Slave.prototype.mode = function () {
  return this.creep.memory.mode || 'mine'
}

/* Slave = Slave.spawn(spawn, role, name)
 *
 * Spawns a new creep of the Slave type, [CARRY,WORK,MOVE].
 * role (charger, upgrader, builder)
 * name will be autogenerated if not passed
 */
/*  PART | COST
    WORK = 100,
    CARRY = 50,
    MOVE = 50
*/
Slave.spawn = function (spawn, role, name) {
  let availableEnergy = Game.spawns.S1.room.energyAvailable
  let availableParts = maxCreepParts
  let creepParts = []

  // if theres still 'room' to make 2xWork + 1xCarry + 1xMove
  // and enough energy in storage
  while (availableParts >= 4 && availableEnergy >= 300) {
    // pushing parts to array, which will be used to spawn creep
    creepParts.push(WORK)
    creepParts.push(WORK)
    creepParts.push(CARRY)
    creepParts.push(MOVE)

    availableParts = availableParts - 4
    availableEnergy = availableEnergy - 300
  }

  let creepToSpawn = doSpawn({
    parts: creepParts || [WORK, CARRY, MOVE],
    role: role,
    memory: {
      job: 'slave'
    }
  }, spawn, name)

  if (creepToSpawn instanceof Creep) {
    return new Slave(creepToSpawn)
  }

  return creepToSpawn
}

/* Slave.tick()
 *
 * Depending on the Slave's mode, either do that thing, or complain that it
 * can't. So essentially just starting workOrder for the creep.
 * Sometimes withouth reassigning, script just breaks and I need to CTRL+S
 *
 * Returns the value from task.
 *
 * Normally:
 * 0: Normal tick
 * 1: Mode changed e.g. (work -> mine)
 * 2: Nothing to do
 *
 * Some tasks may return other values.
 */
Slave.prototype.tick = function () {
  let f = this[this.mode()]

  if (f) {
    f.apply(this, arguments)
  } else {
    console.log('No function to handle mode ' + this.mode())
  }
}

/* Slave.work()
 *
 * Depending on the Slave's role, do the relevant task.
 *
 * Runs from tick() when the creep is in work mode.
 *
 * If the task causes a change in mode, redo tick().
 *
 * Returns:
 * 0: Normal tick
 * 1: Mode change
 * 2: Nothing to do
 *
 * I guess 1 will never be returned, because it will return the
 * response from the new task if the mode is changed.
 */
Slave.prototype.work = function () {
  let response = 0
  switch (this.role()) {
  case 'charger':
    response = doCharge(this.creep)
    break
  case 'upgrader':
    response = doUpgrade(this.creep)
    break
  case 'builder':
    response = doBuild(this.creep)
    break
  case 'repairer':
    response = doRepair(this.creep)
    break
  default:
    response = doMine(this.creep)
    break
  }

  if (response === 1) {
    // mode changed! Tick again to do the new task
    switch (this.mode()) {
    case 'mine':
      this.creep.say('⛏ MINING')
      break
    case 'withdrawEnergy':
      this.creep.say('💰 GET')
      break
    case 'work':
      this.creep.say('✌ WORK')
      break
    default:
      this.creep.say('🚑🚑🚑 yeeeeeeeet 🚑🚑🚑')
    }

    response = this.tick()
  }
  if (response === 2) {
    // Nothing to do! Builders should repair, and others should upgrade.
    if (response === 2) {
      if (this.creep.role === 'builder') {
        response = doRepair(this.creep)
      } else if (this.creep.role === 'repairer') {
        response = doBuild(this.creep)
      } else {
        response = doUpgrade(this.creep)
      }
    }

    if (response === 2) {
      response = doCharge(this.creep)
    }

    if (response === 2) {
      doUpgrade(this.creep)
    }
  }

  return response
}

Slave.prototype.mine = function () {
  doMine(this.creep)
}

Slave.prototype.withdrawEnergy = function () {
  doWithdrawEnergy(this.creep)
}
module.exports = Slave
